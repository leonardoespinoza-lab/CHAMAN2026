const companies = [
  'DON MARIO',
  'SANTA ROSA',
  'MACROSEED',
  'LIMAGRAIN',
  'BIOCERES',
  'ILLINOIS',
  'PIONEER',
  'BREVANT',
  'CORTEVA',
  'NEOGEN',
  'NIDERA',
  'STINE',
  'BASF',
  'NK',
];
const companyPattern = companies.join('|').replace(/ /g, '\\s+');
const decimalPattern = /\d+,\d+/g;

function number(value) {
  return Number(String(value).replace(',', '.'));
}

function parseLine(line, page) {
  const withoutIndex = line.trim().replace(/^\d+\s+/, '');
  const match = withoutIndex.match(
    new RegExp(`^(.*?)\\s+(${companyPattern})\\s+(\\d+,\\d+)\\s+(.*)$`, 'i'),
  );
  if (!match) throw new Error(`No se pudo interpretar RECSO pagina ${page}: ${line}`);
  const [, cultivar, empresa, gmText, rest] = match;
  const decimals = [...rest.matchAll(decimalPattern)];
  if (decimals.length !== 4) {
    throw new Error(`Cantidad de valores inesperada en pagina ${page}: ${line}`);
  }
  const vuelco = decimals[2];
  const smr = decimals[3];
  const sanitary = rest.slice(vuelco.index + vuelco[0].length, smr.index).trim();
  const mor = rest.slice(smr.index + smr[0].length).trim() || null;
  const tokens = sanitary.split(/\s+/).filter(Boolean);
  const cancro = ['R', 'MR'].includes(tokens[0]) ? tokens.shift() : null;
  const phytophthora = tokens.join('') || null;
  return [
    cultivar.trim(),
    empresa.toUpperCase().replace(/\s+/g, ' '),
    number(gmText),
    cancro,
    phytophthora,
    number(smr[0]),
    mor,
    page,
  ];
}

const rows = blocks.flatMap(([page, raw]) =>
  raw
    .trim()
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => parseLine(line, page)),
);

if (rows.length !== 123) {
  throw new Error(`RECSO 2024/25 incompleto: se esperaban 123 filas y hay ${rows.length}.`);
}

